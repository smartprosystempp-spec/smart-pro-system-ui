'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'dist/smart-pro-light-sizing-review.html'),'utf8');
assert(html.includes('smart-pro-light-sizing-qa-card'));
assert(html.includes('data-sp-canonical-tokens'));
assert(html.includes('data-sp-theme="night"'));
assert(!/<link[^>]+href=|<script[^>]+src=|https?:\/\/|fetch\s*\(|XMLHttpRequest|WebSocket/i.test(html));
for(const x of ['ultra','compact','comfortable','theme','surface','viewport','wallpaper','canvas','stage'])assert(html.includes('id="'+x+'"'),'Missing '+x);
for(const x of ['desktop','tablet','mobile','mobile-small'])assert(html.includes('value="'+x+'"'));
for(const x of ['night','graphite','light'])assert(html.includes('value="'+x+'"'));
for(const x of ['solid','soft-glass','glass'])assert(html.includes('value="'+x+'"'));
for(const x of ['ultra-compact','compact','comfortable'])assert(html.includes("'"+x+"'"));
const parts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(parts.length,2,'Expected bundled runtime and preview controller only');
for(let i=0;i<parts.length;i++)new vm.Script(parts[i][1],{filename:'light-sizing-demo-'+i+'.js'});
assert(html.includes('@container (max-width: 360px)'));
assert(html.includes('@container (max-width: 260px)'));
assert(html.includes('καμία εντολή σε πραγματικό φωτισμό'));
console.log('PASS: self-contained QA2 sizing review, responsive controls and JS parsing');
